-- Grammar Quest private admin code verifier (schema only; NO PASSWORDS HERE).
-- Run for a fresh installation. The admin verifier must then be configured
-- privately in Supabase SQL Editor (never commit its INSERT / UPDATE statement).
create table if not exists public.grammar_admin_config (
  name text primary key check (name='main'),
  salt text not null check (salt ~ '^[0-9a-f]{32}$'),
  password_hash text not null check (password_hash ~ '^[0-9a-f]{64}$'),
  changed_at timestamptz not null default now()
);
alter table public.grammar_admin_config enable row level security;
revoke all on table public.grammar_admin_config from PUBLIC, anon, authenticated;
grant select on table public.grammar_admin_config to service_role;
